package com.example.Varsani.Staff.Store_mrg.Model;

public class DonationModel {

    String donner_name, quantity, donation_status, donation_id;

    public String getDonner_name() {
        return donner_name;
    }

    public void setDonner_name(String donner_name) {
        this.donner_name = donner_name;
    }

    public String getDonation_status() {
        return donation_status;
    }

    public void setDonation_status(String donation_status) {
        this.donation_status = donation_status;
    }

    public String getDonation_id() {
        return donation_id;
    }

    public void setDonation_id(String donation_id) {
        this.donation_id = donation_id;
    }

    public String getQuantity() {
        return quantity;
    }

    public void setQuantity(String quantity) {
        this.quantity = quantity;
    }

}
